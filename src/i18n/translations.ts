const SORTED_REPLACEMENTS = Object.entries(EN_REPLACEMENTS).sort(
  (a, b) => b[0].length - a[0].length
);

export const translateText = (text: string, language: Language): string => {
  if (language === 'zh-CN' || !text) {
    return text;
  }

  const trimmed = text.trim();
  if (EN_REPLACEMENTS[trimmed]) {
    return text.replace(trimmed, EN_REPLACEMENTS[trimmed]);
  }

  let result = text;

  for (const [source, target] of SORTED_REPLACEMENTS) {
    if (source.length <= 1) {
      continue;
    }
    result = result.split(source).join(target);
  }

  return result;
};
